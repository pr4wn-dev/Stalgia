#!/usr/bin/env python3
"""Bake the Code Ape luminance mask from the silverback photograph.

Source: resources/white-silverback.jpg (full-body knuckle-walking gorilla
on black). Converts to grayscale, keys out the black background, lifts
interior fur so anatomy (face, brow, crest, chest, arms, legs) survives,
and embeds an R8 texture in src/effects/ApeMaskData.cpp.

    python3 tools/gen_ape_mask.py
"""
from __future__ import annotations

import os
import struct
import subprocess
import sys
import zlib

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
SRC_JPG = os.path.join(ROOT, "resources", "white-silverback.jpg")
SRC_UPLOAD = os.path.join(ROOT, "uploads", "white-silverback.jpg")
PNG = os.path.join(ROOT, "resources", "ape-mask.png")
PREV = os.path.join(ROOT, "resources", "ape-mask-preview.png")
CPP = os.path.join(ROOT, "src", "effects", "ApeMaskData.cpp")
MAX_H = 720


def png_gray(w: int, h: int, gray: bytes) -> bytes:
    def chunk(tag: bytes, data: bytes) -> bytes:
        return (
            struct.pack(">I", len(data))
            + tag
            + data
            + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF)
        )

    raw = b"".join(b"\x00" + gray[y * w : (y + 1) * w] for y in range(h))
    return (
        b"\x89PNG\r\n\x1a\n"
        + chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 0, 0, 0, 0))
        + chunk(b"IDAT", zlib.compress(raw, 9))
        + chunk(b"IEND", b"")
    )


def png_rgb(w: int, h: int, rgb: bytes) -> bytes:
    def chunk(tag: bytes, data: bytes) -> bytes:
        return (
            struct.pack(">I", len(data))
            + tag
            + data
            + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF)
        )

    raw = b"".join(b"\x00" + rgb[y * w * 3 : (y + 1) * w * 3] for y in range(h))
    return (
        b"\x89PNG\r\n\x1a\n"
        + chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 2, 0, 0, 0))
        + chunk(b"IDAT", zlib.compress(raw, 9))
        + chunk(b"IEND", b"")
    )


def decode_rgb(path: str):
    probe = subprocess.run(
        [
            "ffprobe",
            "-v",
            "error",
            "-select_streams",
            "v:0",
            "-show_entries",
            "stream=width,height",
            "-of",
            "csv=p=0",
            path,
        ],
        capture_output=True,
        text=True,
        check=True,
    )
    w_s, h_s = probe.stdout.strip().split(",")
    w, h = int(w_s), int(h_s)
    raw = subprocess.run(
        ["ffmpeg", "-v", "error", "-i", path, "-f", "rawvideo", "-pix_fmt", "rgb24", "pipe:1"],
        capture_output=True,
        check=True,
    ).stdout
    if len(raw) != w * h * 3:
        raise RuntimeError(f"decode size mismatch {len(raw)} vs {w}x{h}")
    return w, h, raw


def luma_at(rgb: bytes, w: int, x: int, y: int) -> float:
    o = (y * w + x) * 3
    return 0.2126 * rgb[o] + 0.7152 * rgb[o + 1] + 0.0722 * rgb[o + 2]


def flood_background(rgb: bytes, w: int, h: int, thresh: float = 10.0) -> bytearray:
    n = w * h
    bg = bytearray(n)  # 1 = background
    stack = []
    for x, y in ((0, 0), (w - 1, 0), (0, h - 1), (w - 1, h - 1), (w // 2, 0), (w // 2, h - 1)):
        stack.append((x, y))
    while stack:
        x, y = stack.pop()
        i = y * w + x
        if bg[i]:
            continue
        if luma_at(rgb, w, x, y) > thresh:
            continue
        bg[i] = 1
        if x > 0:
            stack.append((x - 1, y))
        if x + 1 < w:
            stack.append((x + 1, y))
        if y > 0:
            stack.append((x, y - 1))
        if y + 1 < h:
            stack.append((x, y + 1))
    return bg


def bbox_of(mask: bytearray, w: int, h: int, inside_is_zero: bool = True):
    xs = []
    ys = []
    for y in range(h):
        row = y * w
        for x in range(w):
            is_bg = mask[row + x] != 0
            if inside_is_zero and not is_bg:
                xs.append(x)
                ys.append(y)
    return min(xs), min(ys), max(xs), max(ys)


def sample_bilinear(src, sw, sh, fx, fy):
    x = min(max(fx, 0.0), sw - 1.0001)
    y = min(max(fy, 0.0), sh - 1.0001)
    x0 = int(x)
    y0 = int(y)
    x1 = min(x0 + 1, sw - 1)
    y1 = min(y0 + 1, sh - 1)
    tx = x - x0
    ty = y - y0
    a = src[y0 * sw + x0]
    b = src[y0 * sw + x1]
    c = src[y1 * sw + x0]
    d = src[y1 * sw + x1]
    return (a * (1 - tx) + b * tx) * (1 - ty) + (c * (1 - tx) + d * tx) * ty


def percentile(vals, p):
    if not vals:
        return 0.0
    s = sorted(vals)
    i = int(round((len(s) - 1) * p))
    return float(s[i])


def write_cpp(w: int, h: int, gray: bytes) -> None:
    lines = [
        "// Auto-generated by tools/gen_ape_mask.py — do not edit by hand.",
        "// R8 luminance. 0 = outside (black key). Interior holds photograph shading.",
        '#include "effects/ApeMaskData.h"',
        "",
        f"const int kApeMaskW = {w};",
        f"const int kApeMaskH = {h};",
        "const unsigned char kApeMask[] = {",
    ]
    n = len(gray)
    for i in range(0, n, 24):
        chunk = gray[i : i + 24]
        lines.append("    " + ", ".join(str(b) for b in chunk) + ",")
    lines.append("};")
    lines.append(f"const int kApeMaskBytes = {n};")
    lines.append("")
    os.makedirs(os.path.dirname(CPP), exist_ok=True)
    with open(CPP, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))


def main() -> int:
    src = SRC_JPG if os.path.isfile(SRC_JPG) else SRC_UPLOAD
    if not os.path.isfile(src):
        print("missing white-silverback.jpg", file=sys.stderr)
        return 1
    w, h, rgb = decode_rgb(src)
    bg = flood_background(rgb, w, h, thresh=10.0)
    x0, y0, x1, y1 = bbox_of(bg, w, h)
    pad = int(round(0.03 * max(x1 - x0 + 1, y1 - y0 + 1)))
    x0 = max(0, x0 - pad)
    y0 = max(0, y0 - pad)
    x1 = min(w - 1, x1 + pad)
    y1 = min(h - 1, y1 + pad)
    cw, ch = x1 - x0 + 1, y1 - y0 + 1

    interior = []
    crop = bytearray(cw * ch)
    for y in range(ch):
        for x in range(cw):
            sx, sy = x0 + x, y0 + y
            if bg[sy * w + sx]:
                crop[y * cw + x] = 0
            else:
                v = luma_at(rgb, w, sx, sy)
                crop[y * cw + x] = 1  # mark inside
                interior.append(v)

    lo = percentile(interior, 0.04)
    hi = max(lo + 8.0, percentile(interior, 0.98))
    luma = bytearray(cw * ch)
    for y in range(ch):
        for x in range(cw):
            sx, sy = x0 + x, y0 + y
            if bg[sy * w + sx]:
                luma[y * cw + x] = 0
                continue
            v = (luma_at(rgb, w, sx, sy) - lo) / (hi - lo)
            v = 0.0 if v < 0 else 1.0 if v > 1 else v
            # Keep dark fur visible; stretch highlights for crest/back/face.
            v = 0.18 + 0.82 * (v ** 0.85)
            luma[y * cw + x] = int(v * 255 + 0.5)

    scale = min(1.0, MAX_H / float(ch))
    ow = max(2, int(round(cw * scale)))
    oh = max(2, int(round(ch * scale)))
    out = bytearray(ow * oh)
    for y in range(oh):
        fy = (y + 0.5) * ch / oh - 0.5
        for x in range(ow):
            fx = (x + 0.5) * cw / ow - 0.5
            out[y * ow + x] = int(sample_bilinear(luma, cw, ch, fx, fy) + 0.5)

    os.makedirs(os.path.join(ROOT, "resources"), exist_ok=True)
    with open(PNG, "wb") as f:
        f.write(png_gray(ow, oh, bytes(out)))
    prev = bytearray(ow * oh * 3)
    for i, v in enumerate(out):
        prev[i * 3] = prev[i * 3 + 1] = prev[i * 3 + 2] = v
    with open(PREV, "wb") as f:
        f.write(png_rgb(ow, oh, bytes(prev)))
    write_cpp(ow, oh, bytes(out))
    nz = sum(1 for b in out if b > 0)
    print(f"source {w}x{h} crop {cw}x{ch} -> {ow}x{oh} inside={nz}/{ow*oh}")
    print(f"wrote {PNG}")
    print(f"wrote {PREV}")
    print(f"wrote {CPP} ({os.path.getsize(CPP)} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
